/**
 * 説明文の既定の長さ。
 *
 * 各サービスが独自の位置で省略するため「正解」はありません。日本語で
 * 2〜3文が入る長さにしています。
 */
const MAX_LENGTH = 120;

/**
 * 本文から共有用の説明文を作る（spec §18）。
 *
 * フロントマターに `description` が無いときの代わりです。マークダウンの
 * 記号を落として1行に畳み、上限で切り詰めます。
 *
 * **アンダースコアは落としません。** `0_1.png` のようなファイル名や識別子が
 * 本文に出てくるため、`_強調_` を拾うより壊さないほうを選びました。
 */
export function buildDescription(content: string, maxLength = MAX_LENGTH): string {
  const text = content
    // コードは説明文にならない。中身ごと落とす
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/~~~[\s\S]*?~~~/g, " ")
    // 画像を先に落とす。![alt](src) は [text](url) を含むため、
    // 順番を逆にすると ! だけが残る
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    // リンクは文字だけ残す
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/<!--[\s\S]*?-->/g, " ")
    // 水平線。箇条書きの記号より先に見る（- - - を箇条書きと取らないため）
    .replace(/^[ \t]{0,3}([-*_])[ \t]*(\1[ \t]*){2,}$/gm, " ")
    // 行頭の記号
    .replace(/^[ \t]{0,3}#{1,6}[ \t]+/gm, " ")
    .replace(/^[ \t]{0,3}>[ \t]?/gm, " ")
    .replace(/^[ \t]{0,3}[-*+][ \t]+/gm, " ")
    .replace(/^[ \t]{0,3}\d+\.[ \t]+/gm, " ")
    // 表の区切り行（| --- | :--: |）は中身を持たない。罫線より先に行ごと落とす
    .replace(/^[ \t]*\|[ \t:|-]+\|[ \t]*$/gm, " ")
    // 表の罫線
    .replace(/^[ \t]*\|.*\|[ \t]*$/gm, (row) => row.replace(/\|/g, " "))
    // 強調・インラインコード・取り消し線
    .replace(/[*`~]/g, "")
    .replace(/\s+/g, " ")
    .trim();

  if (text.length <= maxLength) return text;

  // 切った印を付ける。付けないと文が途中で終わったように見える
  return `${text.slice(0, maxLength).trimEnd()}…`;
}
